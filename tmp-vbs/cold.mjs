import { chromium } from 'playwright'
const BASE = 'https://volleyball-stats-7xq.pages.dev'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })
const page = await ctx.newPage()
let t0 = Date.now()
await page.goto(`${BASE}/#/search?q=${encodeURIComponent('Anni Mäkeläinen')}`)
await page.locator('[data-testid=search-players] a[href*="/player/56961"]').waitFor({ timeout: 60000 })
console.log('cold player search to first hit ms', Date.now() - t0)
await page.locator('[data-testid=search-teams] h2').waitFor()
const teamsTxt = await page.locator('[data-testid=search-teams]').innerText()
console.log('teams section for a player name:', teamsTxt.replace(/\n/g, ' | ').slice(0, 200))
t0 = Date.now()
await page.goto(`${BASE}/#/search?q=${encodeURIComponent('VanLe')}`)
await page.locator('[data-testid=search-teams] a[href*="/team/"]').first().waitFor({ timeout: 60000 })
console.log('warm team search VanLe ms', Date.now() - t0, (await page.locator('[data-testid=search-teams] a[href*="/team/"]').allInnerTexts()).slice(0, 5).map((x) => x.replace(/\n/g, ' ')).join(' || '))
await page.goto(`${BASE}/#/competition/vb2026esuomi/category/U13T`)
await page.locator('a[href*="/match/"]').first().waitFor({ timeout: 60000 })
const heads = await page.locator('main h3').allInnerTexts()
const halls = await page.locator('main p.uppercase').allInnerTexts()
console.log('U13T tournament days:', heads.slice(0, 6).join(' | '), '| halls:', halls.slice(0, 4).join(' | '), '| match links', await page.locator('a[href*="/match/"]').count())
await page.screenshot({ path: '/workspace/pelipaiva/tmp-vbs/live-u13t.png' })
await browser.close()
