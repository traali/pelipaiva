import { chromium } from 'playwright'
const BASE = process.env.BASE || 'http://localhost:4173'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true })
const page = await ctx.newPage()
// Origin answers 403, proxy answers 200 with an error body: the two real failure shapes.
await page.route('**/lentopallo-api.torneopal.net/**', (r) => r.fulfill({ status: 403, body: '' }))
await page.route('**/taso-proxy.sakkoja.workers.dev/**', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: '{"call":{"status":"error","http":403},"error":"upstream"}' }))
await page.goto(`${BASE}/#/search?q=${encodeURIComponent('Anni Mäkeläinen')}`)
await page.getByRole('button', { name: 'Yritä uudelleen' }).waitFor({ timeout: 30000 })
const body = await page.locator('main').innerText()
console.log('SEARCH (all TASO failing):\n' + body)
console.log('says "Ei osumia"?', body.includes('Ei osumia'), '| says "Ei pelaajia"?', body.includes('Ei pelaajia'))
await page.goto(`${BASE}/#/match/803471`)
await page.getByRole('button', { name: 'Yritä uudelleen' }).waitFor({ timeout: 30000 })
console.log('MATCH:', (await page.locator('main').innerText()).replace(/\n/g, ' '))
await page.goto(`${BASE}/#/group/power2026/PD/1`)
await page.getByRole('button', { name: 'Yritä uudelleen' }).waitFor({ timeout: 30000 })
console.log('GROUP:', (await page.locator('main').innerText()).replace(/\n/g, ' '), '| table?', await page.locator('table').count())
await browser.close()
